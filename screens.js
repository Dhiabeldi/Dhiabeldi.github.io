/* v9.2 · "Every screen" (screens.html, from prototype p07).
   Every tile and caption is static markup (so i18n.js translates it); this file only filters, counts, lifts a
   screen on hover with the decision it shows, and opens it large in a <dialog> with prev / next, growing out of
   its tile (a ghost FLIP). No library. Loaded after i18n.js and word-hover.js.
   Generated by Claude (AI assistant) for Mohamed Dhia Beldi. */
(function () {
  'use strict';
  var D = document;
  var REDUCED = matchMedia('(prefers-reduced-motion: reduce)').matches;
  var $ = function (s, r) { return (r || D).querySelector(s); };
  var $$ = function (s, r) { return Array.prototype.slice.call((r || D).querySelectorAll(s)); };

  /* the mobile menu is bound once for every page in transitions.js */

  var wall = $('#scr-wall'), bar = $('#scr-bar');
  if (!wall) return;
  var tiles = $$('.scr-t', wall);
  var CO = {}; // product -> company
  $$('.scr-co', wall).forEach(function (c) { $$('.scr-blk', c).forEach(function (b) { CO[b.dataset.p] = c.dataset.co; }); });
  var NAME = {}, HREF = {};
  $$('.scr-blk', wall).forEach(function (b) { NAME[b.dataset.p] = $('h3', b).textContent.trim(); HREF[b.dataset.p] = $('.scr-bh a', b).getAttribute('href'); });
  var showBefore = false, filt = 'all';
  var live = function (t) { return showBefore || t.dataset.kind !== 'before'; };
  var inF = function (t) { return filt === 'all' || filt === t.dataset.p || filt === CO[t.dataset.p]; };
  var txt = function (t, sel) { return ($(sel, t) || {}).textContent || ''; };

  function counts() {
    var n = function (f) { return tiles.filter(function (t) { return live(t) && (f === 'all' || f === t.dataset.p || f === CO[t.dataset.p]); }).length; };
    $$('output[data-c]', bar).forEach(function (o) { o.textContent = n(o.dataset.c); });
    // the headings count what is on the wall right now
    $$('output[data-n]', wall).forEach(function (o) {
      var k = o.dataset.n;
      o.textContent = tiles.filter(function (t) { return live(t) && inF(t) && (k === t.dataset.p || k === CO[t.dataset.p]); }).length;
    });
  }
  function apply(animate) {
    $$('.scr-f', bar).forEach(function (b) { b.setAttribute('aria-pressed', b.dataset.f === filt ? 'true' : 'false'); });
    var shown = [];
    tiles.forEach(function (t) { var on = live(t) && inF(t); if (on && t.hidden) shown.push(t); t.hidden = !on; });
    $$('.scr-blk', wall).forEach(function (b) { b.hidden = !(filt === 'all' || filt === b.dataset.p || filt === CO[b.dataset.p]); });
    $$('.scr-co', wall).forEach(function (c) { c.hidden = !$$('.scr-blk', c).some(function (b) { return !b.hidden; }); });
    counts();
    if (animate && !REDUCED) {
      tiles.forEach(function (t) { t.classList.remove('enter'); });
      void wall.offsetWidth;
      tiles.filter(function (t) { return !t.hidden; }).slice(0, 40).forEach(function (t, i) { t.style.animationDelay = (i * 15) + 'ms'; t.classList.add('enter'); });
    }
  }
  function swap(fn) {
    if (REDUCED) { fn(); return; }
    wall.classList.add('swap');
    setTimeout(function () { fn(); wall.classList.remove('swap'); }, 180);
  }
  bar.addEventListener('click', function (e) {
    var b = e.target.closest('.scr-f'); if (!b) return;
    filt = b.dataset.f;
    swap(function () { apply(true); });
    var top = wall.getBoundingClientRect().top + scrollY - 140;
    if (scrollY > top) scrollTo({ top: top, behavior: REDUCED ? 'auto' : 'smooth' });
  });
  var sw = $('#scr-before');
  sw.addEventListener('change', function () {
    showBefore = sw.checked;
    if (showBefore && filt !== 'all' && filt !== 'zum' && filt !== 'ZUM-IT') filt = 'zum';
    swap(function () { apply(true); });
  });
  apply(false);
  // switching language rewrites the filter labels from the dictionary: count again
  addEventListener('i18n:changed', counts);
  addEventListener('scroll', function () { bar.classList.toggle('stuck', bar.getBoundingClientRect().top <= 68); }, { passive: true });

  /* ---------- hover: lift the screen, the rest step back, a card says what it shows ---------- */
  var tip = $('#scr-tip');
  var label = function (t) { return CO[t.dataset.p] + ' · ' + NAME[t.dataset.p]; };
  function show(t) {
    tiles.forEach(function (x) { x.classList.toggle('on', x === t); });
    wall.classList.toggle('hov', !!t);
    if (!t) { tip.classList.remove('on'); return; }
    $('.k', tip).textContent = label(t); $('.t', tip).textContent = txt(t, '.t'); $('.d', tip).textContent = txt(t, '.d');
    var r = t.getBoundingClientRect(), tw = tip.offsetWidth, th = tip.offsetHeight;
    var x = Math.min(Math.max(16, r.left + r.width / 2 - tw / 2), innerWidth - tw - 16);
    var y = r.bottom + 14; if (y + th > innerHeight - 12) y = r.top - th - 14; if (y < 80) y = Math.min(innerHeight - th - 12, r.bottom + 14);
    tip.style.left = x + 'px'; tip.style.top = y + 'px'; tip.classList.add('on');
  }
  if (matchMedia('(hover: hover)').matches) {
    wall.addEventListener('pointerover', function (e) { var t = e.target.closest('.scr-t'); if (t) show(t); });
    wall.addEventListener('pointerleave', function () { show(null); });
    wall.addEventListener('pointermove', function (e) { if (!e.target.closest('.scr-t')) show(null); });
    addEventListener('scroll', function () { show(null); }, { passive: true });
  }
  wall.addEventListener('focusin', function (e) { var t = e.target.closest('.scr-t'); if (t && t.matches(':focus-visible')) show(t); });
  wall.addEventListener('focusout', function () { show(null); });

  /* ---------- lightbox: the screen grows out of its tile; prev / next within the current filter ---------- */
  var lb = $('#scr-lb'), scroller = $('.lb-scroll', lb), img = $('img', scroller), side = $('.lb-side', lb), stage = $('[data-lb="stage"]', lb);
  var cur = null;
  var list = function () { return tiles.filter(function (t) { return !t.hidden; }); };
  var src = function (t) { return $('img', t).getAttribute('src'); };
  function fill(t) {
    cur = t;
    var ph = t.classList.contains('ph'), w = +t.dataset.w, h = +t.dataset.h;
    img.src = src(t); img.alt = label(t) + ': ' + txt(t, '.t');
    scroller.classList.toggle('ph', ph);
    // size the frame to the screen: it fits the stage; phones and long page captures scroll inside it
    var st = stage.getBoundingClientRect(), small = innerWidth <= 760;
    var padW = st.width - (small ? 28 : 64), padH = st.height - (small ? 74 : 56);
    scroller.style.width = Math.round(Math.max(180, Math.min(padW, padH * (ph ? 660 / 1428 : w / h)))) + 'px';
    scroller.style.maxHeight = Math.round(padH) + 'px'; scroller.scrollTop = 0;
    $('.k', side).textContent = label(t); $('.t', side).textContent = txt(t, '.t'); $('.d', side).textContent = txt(t, '.d');
    var mk = t.dataset.kind || t.dataset.p;
    $$('[data-meta]', side).forEach(function (m) { m.hidden = m.dataset.meta !== mk; });
    $('.lb-a', side).href = HREF[t.dataset.p];
    var L = list(); $('.cnt', side).textContent = (L.indexOf(t) + 1) + ' / ' + L.length;
  }
  function ghost(from, a, b, dur, done) {
    var g = D.createElement('div'); g.className = 'scr-ghost'; g.innerHTML = '<img src="' + from + '" alt="">';
    g.style.left = a.left + 'px'; g.style.top = a.top + 'px'; g.style.width = a.width + 'px'; g.style.height = a.height + 'px';
    D.body.appendChild(g);
    var an = g.animate([{ left: a.left + 'px', top: a.top + 'px', width: a.width + 'px', height: a.height + 'px' },
      { left: b.left + 'px', top: b.top + 'px', width: b.width + 'px', height: b.height + 'px' }],
      { duration: dur, easing: 'cubic-bezier(.65,0,.35,1)', fill: 'forwards' });
    an.onfinish = function () { if (done) done(); g.remove(); };
  }
  var rect = function (el) { var r = el.getBoundingClientRect(); return { left: r.left, top: r.top, width: r.width, height: r.height }; };
  function fade(els, from, to, dx, dur, delay) {
    els.forEach(function (el) { el.animate([{ opacity: from, transform: 'translateX(' + dx[0] + 'px)' }, { opacity: to, transform: 'translateX(' + dx[1] + 'px)' }],
      { duration: dur, delay: delay || 0, easing: 'cubic-bezier(.2,.8,.2,1)', fill: 'both' }); });
  }
  function open(t) {
    show(null); lb.showModal(); fill(t);
    if (REDUCED) return;
    var a = rect(t);
    scroller.style.opacity = 0; side.style.opacity = 0;
    var go = function () {
      t.style.visibility = 'hidden';
      ghost(src(t), a, rect(scroller), 600, function () { scroller.style.opacity = ''; t.style.visibility = ''; });
      side.style.opacity = ''; fade([side], 0, 1, [20, 0], 500, 250);
    };
    if (img.complete) requestAnimationFrame(go); else img.addEventListener('load', go, { once: true });
  }
  function close() {
    if (!lb.open) return;
    var t = cur && !cur.hidden ? cur : null;
    if (REDUCED || !t) { lb.close(); return; }
    t.scrollIntoView({ block: 'nearest' });
    var a = rect(scroller), b = rect(t);
    scroller.style.opacity = 0; fade([side], 1, 0, [0, 0], 200);
    t.style.visibility = 'hidden';
    ghost(src(t), a, b, 500, function () { t.style.visibility = ''; });
    setTimeout(function () { lb.close(); scroller.style.opacity = ''; side.getAnimations().forEach(function (x) { x.cancel(); }); }, 260);
  }
  function step(d) {
    var L = list(), k = L.indexOf(cur), n = L[(k + d + L.length) % L.length];
    if (REDUCED) { fill(n); return; }
    fade([scroller, side], 1, 0, [0, -24 * d], 180);
    setTimeout(function () { fill(n); fade([scroller, side], 0, 1, [24 * d, 0], 320); }, 180);
  }
  wall.addEventListener('click', function (e) { var t = e.target.closest('.scr-t'); if (t) open(t); });
  $('[data-lb="prev"]', lb).addEventListener('click', function () { step(-1); });
  $('[data-lb="next"]', lb).addEventListener('click', function () { step(1); });
  $('[data-lb="close"]', lb).addEventListener('click', close);
  lb.addEventListener('cancel', function (e) { e.preventDefault(); close(); });
  lb.addEventListener('click', function (e) { if (e.target === lb || e.target === stage) close(); });
  lb.addEventListener('keydown', function (e) {
    if (e.key === 'ArrowRight') { e.preventDefault(); step(1); }
    if (e.key === 'ArrowLeft') { e.preventDefault(); step(-1); }
  });
  var sx = null;
  scroller.addEventListener('pointerdown', function (e) { if (e.pointerType !== 'mouse') sx = e.clientX; });
  scroller.addEventListener('pointerup', function (e) { if (sx === null) return; var dx = e.clientX - sx; sx = null; if (Math.abs(dx) > 50) step(dx < 0 ? 1 : -1); });
  addEventListener('resize', function () { if (lb.open && cur) fill(cur); });
})();
