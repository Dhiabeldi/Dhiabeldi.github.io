/* v9.2 · CV as a changelog (from concepts/pages-12/p08-cv-changelog.html).
   Generated by Claude (AI assistant) for Mohamed Dhia Beldi.
   Curved ring-screen thumbnails, one EN/FR switch for every PDF download (assets/cv-3a7b1ab257ba/), the All · Roles · Products ·
   Certifications filter with a GSAP Flip morph, the version rail, calm entry. Reduced motion: no Flip, no entry. */
(function () {
  'use strict';

  /* the mobile menu is bound once for every page in transitions.js */

  var reduce = matchMedia('(prefers-reduced-motion: reduce)').matches;
  var $ = function (s, r) { return (r || document).querySelector(s); };
  var $$ = function (s, r) { return [].slice.call((r || document).querySelectorAll(s)); };
  if (window.gsap && window.Flip && window.ScrollTrigger) gsap.registerPlugin(ScrollTrigger, Flip);
  var PDF = 'assets/cv-3a7b1ab257ba/', F = { en: ['Mohamed-Dhia-Beldi-CV-EN.pdf', 'Mohamed-Dhia-Beldi-CV-EN-ATS.pdf'], fr: ['Mohamed-Dhia-Beldi-CV-FR.pdf', 'Mohamed-Dhia-Beldi-CV-FR-ATS.pdf'] };

  /* ---------- curved ring-screen thumbnails (the same cylinder slices as the hero ring) ---------- */
  function curves() {
    $$('.cvl-cs').forEach(function (el) {
      var box = el.parentNode, W = Math.min(box.clientWidth - 30, 230), H = Math.round(W / 1.55);
      el.style.width = W + 'px'; el.style.height = H + 'px'; el.innerHTML = '';
      var n = 10, A = 56 * Math.PI / 180, R = W / A, w = W / n, iw = +el.dataset.w, ih = +el.dataset.h;
      var s = Math.max(W / iw, H / ih), bw = iw * s, bh = ih * s, ox = (W - bw) / 2, oy = el.dataset.fit === 'top' ? 0 : (H - bh) / 2;
      for (var i = 0; i < n; i++) {
        var phi = (-W / 2 + (i + 0.5) * w) / R, sh = (Math.abs(phi) / (A / 2) * 0.15).toFixed(3);
        var d = document.createElement('i'); d.className = 'cvl-sl';
        d.style.width = (w + 1) + 'px'; d.style.left = (W / 2 - w / 2 - 0.5) + 'px';
        d.style.backgroundImage = 'linear-gradient(rgba(46,16,101,' + sh + '),rgba(46,16,101,' + sh + ')),url("' + el.dataset.src + '")';
        d.style.backgroundSize = '100% 100%,' + bw + 'px ' + bh + 'px';
        d.style.backgroundPosition = '0 0,' + (ox - i * w + 0.5) + 'px ' + oy + 'px';
        d.style.transform = 'translateZ(' + R + 'px) rotateY(' + (-phi) + 'rad) translateZ(' + (-R) + 'px)';
        if (i === 0) d.style.borderRadius = '7px 0 0 7px'; if (i === n - 1) d.style.borderRadius = '0 7px 7px 0';
        el.appendChild(d);
      }
      el.style.transform = 'translateZ(' + (-W * 0.2) + 'px)';
      el.style.filter = 'drop-shadow(0 18px 18px rgba(46,16,101,.25))';
    });
  }
  curves();
  var rz; addEventListener('resize', function () { clearTimeout(rz); rz = setTimeout(curves, 150); });

  /* ---------- download: one language switch drives every download button on the page.
     It starts on the site's language; the button labels stay in the site's language (i18n.js owns them). ---------- */
  function setCv(L) {
    $$('[data-cvlang]').forEach(function (o) { o.setAttribute('aria-pressed', o.dataset.cvlang === L ? 'true' : 'false'); });
    $$('[data-cv="main"]').forEach(function (a) { a.href = PDF + F[L][0]; });
    $$('[data-cv="ats"]').forEach(function (a) { a.href = PDF + F[L][1]; });
  }
  var picked = false;
  document.addEventListener('click', function (e) {
    var b = e.target.closest && e.target.closest('[data-cvlang]'); if (!b) return;
    picked = true; setCv(b.dataset.cvlang);
  });
  function siteLang() { return document.documentElement.lang === 'fr' ? 'fr' : 'en'; }
  setCv(siteLang());

  /* ---------- counts and filter ---------- */
  var ents = $$('.cvl-ent'), vers = $$('.cvl-ver');
  var group = function (t) { return t === 'edu' || t === 'vol' ? 'role' : t; };
  var counts = { all: ents.length, role: 0, shipped: 0, cert: 0 };
  ents.forEach(function (e) { counts[group(e.dataset.type)]++; });
  function fillCounts() { $$('[data-count]').forEach(function (s) { s.textContent = counts[s.dataset.count]; }); }
  fillCounts();

  var tabs = $$('.cvl-cl-tabs [role="tab"]'), current = 'all';
  function apply(f) {
    ents.forEach(function (e) { e.classList.toggle('is-hidden', f !== 'all' && group(e.dataset.type) !== f); });
    vers.forEach(function (v) {
      var any = $$('.cvl-ent', v).some(function (e) { return !e.classList.contains('is-hidden'); });
      v.classList.toggle('is-hidden', !any);
      $('.cvl-vend', v).classList.toggle('is-hidden', f !== 'all');
    });
    $('#earlier').classList.toggle('is-hidden', f !== 'all' && f !== 'role');
  }
  function setFilter(f) {
    if (f === current) return; current = f;
    tabs.forEach(function (t) { var on = t.dataset.filter === f; t.setAttribute('aria-selected', on ? 'true' : 'false'); t.tabIndex = on ? 0 : -1; });
    // v9.3 (P1): only what is on screen (before or after) is flipped; the rest just takes its place. Flipping all
    // 60-odd entries, nested and absolute, blocked 0.1 s per click (0.5 s on a slower CPU).
    var targets = $$('.cvl-ent, .cvl-ver, .cvl-ver-h, .cvl-vend, #earlier');
    var near = function (el) { if (el.classList.contains('is-hidden')) return false; var r = el.getBoundingClientRect(); return r.bottom > -120 && r.top < innerHeight + 120; };
    var before = targets.filter(near);
    var state = window.Flip && window.gsap && !reduce ? Flip.getState(before) : null;
    apply(f);
    if (state) {
      var after = targets.filter(near), both = before.concat(after.filter(function (e) { return before.indexOf(e) < 0; }));
      Flip.from(state, { targets: both, duration: 0.55, ease: 'power3.inOut', absolute: true, nested: true, prune: true,
        onEnter: function (els) { return gsap.fromTo(els, { opacity: 0, y: 16 }, { opacity: 1, y: 0, duration: 0.45, delay: 0.12, stagger: 0.015 }); },
        onLeave: function (els) { return gsap.to(els, { opacity: 0, duration: 0.2 }); },
        onComplete: function () { if (window.ScrollTrigger) ScrollTrigger.refresh(); } });
    }
    var top = $('.cvl-cl-main').getBoundingClientRect().top + scrollY - 70;
    if (scrollY > top) window.scrollTo({ top: top, behavior: reduce ? 'auto' : 'smooth' });
    try { history.replaceState(null, '', f === 'all' ? location.pathname : '#' + f); } catch (e) {}
  }
  tabs.forEach(function (t, i) {
    t.tabIndex = t.getAttribute('aria-selected') === 'true' ? 0 : -1;
    t.addEventListener('click', function () { setFilter(t.dataset.filter); });
    t.addEventListener('keydown', function (e) {
      var d = e.key === 'ArrowRight' ? 1 : e.key === 'ArrowLeft' ? -1 : 0; if (!d) return;
      e.preventDefault(); var n = tabs[(i + d + tabs.length) % tabs.length]; n.focus(); setFilter(n.dataset.filter);
    });
  });
  var h = location.hash.slice(1); if (counts[h] !== undefined && h !== 'all') { current = 'x'; setFilter(h); }

  /* switching language replaces the tab labels (and their empty count spans) */
  addEventListener('i18n:changed', function () { fillCounts(); if (!picked) setCv(siteLang()); });

  /* ---------- version rail: which version you are reading ---------- */
  var railA = $$('#rail a');
  function spy() {
    var y = innerHeight * 0.35, cur = '3';
    vers.forEach(function (v) { if (!v.classList.contains('is-hidden') && v.getBoundingClientRect().top < y) cur = v.dataset.v; });
    $$('#rail a').forEach(function (a) { a.classList.toggle('on', a.dataset.v === cur); });
  }
  addEventListener('scroll', spy, { passive: true }); spy();

  /* ---------- calm entry: entries rise as they come in (same grammar as the other pages) ---------- */
  if (!reduce && window.gsap && window.ScrollTrigger) {
    // arriving from a nav word (transitions.js), the title is already there: only the rest rises
    var viaNav = document.documentElement.classList.contains('tr-in-nav');
    gsap.from(viaNav ? '.cvl-cl-head .sub, .cvl-vcard' : '.cvl-cl-head h1, .cvl-cl-head .sub, .cvl-vcard', { y: 24, opacity: 0, duration: 0.9, stagger: 0.07, ease: 'expo.out' });
    var below = $$('.cvl-ent, .cvl-ver-h').filter(function (e) { return e.getBoundingClientRect().top > innerHeight * 0.92; });
    gsap.set(below, { opacity: 0, y: 22 });
    ScrollTrigger.batch(below, { start: 'top 92%', once: true,
      onEnter: function (b) { gsap.fromTo(b, { y: 22, opacity: 0 }, { y: 0, opacity: 1, duration: 0.7, stagger: 0.06, ease: 'expo.out', overwrite: true }); } });
    $$('.cvl-thumb-w').forEach(function (t) {
      gsap.fromTo(t, { '--lift': 1 }, { '--lift': 0, duration: 1.1, ease: 'expo.out',
        scrollTrigger: { trigger: t, start: 'top 88%', once: true } });
    });
  }
})();
