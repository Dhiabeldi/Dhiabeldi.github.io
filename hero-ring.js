const wrapA = a => { a %= Math.PI * 2; if (a > Math.PI) a -= Math.PI * 2; if (a < -Math.PI) a += Math.PI * 2; return a; };
function updateParts() {
  items.forEach(it => {
    it.sv += (-it.sq * .32) - it.sv * .22; it.sq += it.sv;
    let x, y, a, sc = 1, op = 1;
    if (it.mode === 'gone') { if (it.op !== 0) { it.el.style.opacity = 0; it.op = 0; } return; }
    if (it.mode === 'body') { x = it.b.position.x; y = it.b.position.y; a = it.b.angle; }
    else {
      const f = it.f, t = f.t, u = 1 - t, P = panelScreen(panels[it.pi], f.ox, f.oy);
      const sEnd = THREE.MathUtils.clamp(P.ph * (it.meme ? 1.02 : 0.4) / it.h, 0.2, it.meme ? 1.8 : 1);
      if (it.mode === 'fly') {
        x = u * u * f.S.x + 2 * u * t * f.C.x + t * t * P.x; y = u * u * f.S.y + 2 * u * t * f.C.y + t * t * P.y;
        a = f.a0 * (1 - t) + f.spin * Math.sin(Math.PI * t); sc = 1 + (sEnd - 1) * t;
        op = t < f.fade ? 1 : 1 - (t - f.fade) / (1 - f.fade);
      } else { // 'back': from the screen to a drop point above the name
        x = u * u * P.x + 2 * u * t * f.C.x + t * t * f.E.x; y = u * u * P.y + 2 * u * t * f.C.y + t * t * f.E.y;
        a = f.spin * Math.sin(Math.PI * t) + f.a1 * t; sc = sEnd + (1 - sEnd) * t; op = Math.min(1, t / .22);
      }
    }
    if (op !== it.op) { it.el.style.opacity = op; it.op = op; }
    const s = it.sq;
    it.el.style.transform = `translate(${x - it.w / 2}px,${y - it.h / 2}px) rotate(${a}rad) scale(${(1 - s) * sc},${(1 + s) * sc})`;
  });
}

