      '<path d="M' + (x1 + 14) + ' ' + h * 0.3 + ' L' + (x1 + 44) + ' ' + h * 0.38 + '"/>' +
      '<path d="M' + x2 + ' -4 L' + (x2 - 10) + ' ' + h * 0.36 + ' L' + (x2 + 12) + ' ' + h * 0.6 + ' L' + (x2 - 6) + ' ' + (h + 4) + '"/>' +
      '<path d="M' + (x2 + 12) + ' ' + h * 0.6 + ' L' + (x2 + 40) + ' ' + h * 0.7 + '"/>';
    $$('path', svg).forEach(function (p) { var L = p.getTotalLength(); p.style.strokeDasharray = L; p.style.strokeDashoffset = reduce ? 0 : L; p.dataset.l = L; });
