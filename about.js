    if (laneTl) { laneTl.clear(); } else { laneTl = pinTl(2); }
    var tl = laneTl, chars = $$('#bub .ab-c'), paths = $$('#crack path');
    gsap.set('#bub', { opacity: 1, x: 0 }); gsap.set('#crack', { opacity: 1 });
    gsap.set(shards, { opacity: 0 }); gsap.set('#ghost', { opacity: 0 });
    tl.to(chars, { opacity: 1, duration: 0.004, stagger: 0.32 / chars.length }, 0.02)
      .to({}, { duration: 0.08 });
    paths.forEach(function (p, i) { tl.to(p, { strokeDashoffset: 0, duration: 0.08, ease: 'power1.in' }, 0.44 + i * 0.03); });
    tl.to('#bub', { x: 2, duration: 0.01, repeat: 5, yoyo: true }, 0.56)
      .set('#bub', { opacity: 0 }, 0.6).set('#crack', { opacity: 0 }, 0.6)
      .set(shards, { opacity: 1 }, 0.6);
    shards.forEach(function (s, i) {
      tl.to(s, { y: innerHeight * 0.75, x: (i - 1) * 90, rotate: (i - 1) * 26 + (i === 1 ? 10 : 0), opacity: 0, duration: 0.24, ease: 'power2.in' }, 0.61 + i * 0.025);
    });
    tl.to('#ghost', { opacity: 1, duration: 0.08 }, 0.74)
      .fromTo('#reply', { opacity: 0, y: 16 }, { opacity: 1, y: 0, duration: 0.1, ease: 'power2.out' }, 0.8)
