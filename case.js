/* v9.2 · the shared case-study template (case.css, namespaced cs-).
   ---------------------------------------------------------------------------
   1. The layers chapter (from prototype p04): tokens, then components, then the shipped screen land on each
      other as you scroll, then the stack turns to face you. Scrubbed by scroll, no library.
   2. Sections and phone rows arrive the same way everywhere (IntersectionObserver adds .in).
   3. The before/after brush (p04, ZUMConnect only): paint the rebuild over the template it inherited.
   4. The next-case door (p05): the next case's cover grows out of a rounded window as you scroll, a violet ring
      counts 0 to 100, and at 100 it opens by itself. Scrolling back cancels; a fast fling waits a little longer.
   Every visible string lives in the HTML (so i18n.js can translate it); this file only shows or hides it.
   Loaded at the end of <body>, after i18n.js and word-hover.js.
   Generated by Claude (AI assistant) for Mohamed Dhia Beldi. */
(function () {
  'use strict';
  var D = document, H = D.documentElement;
  var REDUCED = matchMedia('(prefers-reduced-motion: reduce)').matches;
  var $ = function (s, r) { return (r || D).querySelector(s); };
  var $$ = function (s, r) { return Array.prototype.slice.call((r || D).querySelectorAll(s)); };
  var phone = function () { return innerWidth <= 760; };
  var clamp = function (v, a, b) { return Math.min(b, Math.max(a, v)); };

  /* the mobile menu is bound once for every page in transitions.js */

  /* ---------- 1. the layers chapter ---------- */
  var ease = {
    io: function (t) { return t < .5 ? 2 * t * t : 1 - Math.pow(-2 * t + 2, 2) / 2; },
    out3: function (t) { return 1 - Math.pow(1 - t, 3); }
  };
  // progress of one tween that runs from t0 for d (in timeline units), eased
  function tw(t, t0, d, e) { return (e || ease.io)(clamp((t - t0) / d, 0, 1)); }
  function lerp(a, b, k) { return a + (b - a) * k; }

  $$('.cs-lay').forEach(function (sec) {
    var rig = $('.cs-rig', sec), tok = $('.cs-tok', sec), cmp = $('.cs-cmp', sec), scr = $('.cs-scr', sec);
    if (!rig || !tok || !cmp || !scr) return;
    var parts = $$('.cs-cp', cmp), lbls = $$('.cs-lbl', rig), steps = $$('.cs-steps li', sec), rail = $('.cs-rail', sec);
    var wide = rig.classList.contains('cs-wide');
    var n = Math.max(1, parts.length), stg = Math.min(.32, 2.2 / n);
    // the timeline, in the same units as the prototype: tokens alone, parts land, the screen lands, the stack turns
    var T = { parts: 1.2, scr: Math.max(4.2, 1.2 + stg * (n - 1) + 1.1), turn: 0, end: 0 };
    T.turn = T.scr + 1.9; T.end = T.turn + 3.1;
    var cuts = [0, T.parts, T.scr, T.turn + .5].map(function (t) { return t / T.end; });
    function G() { return phone() ? (wide ? 60 : 80) : (wide ? 110 : 130); }
    function render(p) {
      var t = p * T.end, g = G();
      var turn = tw(t, T.turn, 2.2);
      var rx = lerp(54, 0, turn), rz = lerp(-30, 0, turn);
      var x = lerp(phone() ? 0 : (wide ? 30 : -70), 0, turn), y = lerp(phone() ? 0 : 20, 0, turn);
      rig.style.transform = 'translate3d(' + x + 'px,' + y + 'px,0) rotateX(' + rx + 'deg) rotateZ(' + rz + 'deg)';
      tok.style.transform = 'translateZ(' + lerp(-g, 0, turn) + 'px)';
      tok.style.opacity = 1 - tw(t, T.turn + 1.6, .5);
      cmp.style.opacity = 1 - tw(t, T.turn + 1.6, .5);
      parts.forEach(function (el, i) {
        var k = tw(t, T.parts + i * stg, 1, ease.out3);
        el.style.transform = 'translateZ(' + lerp(260, 0, k) + 'px)';
        el.style.opacity = k;
      });
      var land = tw(t, T.scr, 1.4, ease.out3);
      scr.style.transform = 'translateZ(' + lerp(lerp(g * 3.2, g, land), 0, turn) + 'px)';
      scr.style.opacity = land;
      var lo = 1 - tw(t, T.turn, .6);
      lbls.forEach(function (l) { l.style.opacity = lo; });
      var i = 0; cuts.forEach(function (c, k) { if (p >= c - .001) i = k; });
      steps.forEach(function (li, k) { li.classList.toggle('on', k === i); li.classList.toggle('done', k < i); });
      var on = steps[i]; if (on && rail && !phone()) rail.style.height = (on.offsetTop + 22) + 'px';
    }
    if (REDUCED) { // the exploded stack, still, with every step open
      render(cuts[2] + .05);
      steps.forEach(function (li) { li.classList.add('on'); });
      return;
    }
    var last = -1, raf = 0;
    function tick() {
      raf = 0;
      var r = sec.getBoundingClientRect(), max = sec.offsetHeight - (innerHeight - 67);
      var p = clamp((67 - r.top) / Math.max(1, max), 0, 1);
      if (Math.abs(p - last) < .0005) return;
      // a little smoothing so a wheel step glides instead of jumping
      last = last < 0 ? p : last + (p - last) * .35;
      render(last);
      if (Math.abs(p - last) > .0006) raf = requestAnimationFrame(tick);
    }
    var kick = function () { if (!raf) raf = requestAnimationFrame(tick); };
    addEventListener('scroll', kick, { passive: true });
    addEventListener('resize', function () { last = -1; kick(); });
    // i18n swaps step text, which can change heights: keep the rail on the active step
    addEventListener('i18n:changed', function () { last = -1; kick(); });
    render(0); kick();
  });

  /* ---------- 2. sections arrive the same way everywhere ---------- */
  (function () {
    var els = $$('.cs-up, .cs-phones');
    if (REDUCED || !('IntersectionObserver' in window)) { els.forEach(function (e) { e.classList.add('in'); }); return; }
    var io = new IntersectionObserver(function (en) {
      en.forEach(function (e) { if (e.isIntersecting) { e.target.classList.add('in'); io.unobserve(e.target); } });
    }, { rootMargin: '0px 0px -12% 0px' });
    els.forEach(function (e) { io.observe(e); });
    // printing (and the PDF build) must never meet a hidden section
    addEventListener('beforeprint', function () { els.forEach(function (e) { e.classList.add('in'); }); });
  })();

  /* ---------- 3. the brush ---------- */
  $$('.cs-br').forEach(function (root) {
    var box = $('.cs-br-box', root), c = $('canvas', box), ctx = c.getContext('2d');
    var cur = $('.cs-br-cur', box), hint = $('.cs-br-hint', box);
    var tabs = $$('.cs-br-tabs button', root);
    var mask = D.createElement('canvas'), mx = mask.getContext('2d');
    var tmp = D.createElement('canvas'), tx = tmp.getContext('2d');
    var glow = D.createElement('canvas'), gx = glow.getContext('2d');
    var W = 0, Hh = 0, DP = 1, before = null, after = null, key = '', dirty = true, last = null, auto = null, seen = false, vis = false;
    var load = function (src) { return new Promise(function (r) { var i = new Image(); i.onload = function () { r(i); }; i.onerror = function () { r(null); }; i.src = src; }); };
    function size() {
      var r = box.getBoundingClientRect(); DP = Math.min(devicePixelRatio || 1, 2);
      var nw = Math.round(r.width * DP), nh = Math.round(r.height * DP);
      if (!nw || (nw === W && nh === Hh)) return;
      var keep = null;
      if (W) { keep = D.createElement('canvas'); keep.width = W; keep.height = Hh; keep.getContext('2d').drawImage(mask, 0, 0); }
      W = c.width = mask.width = tmp.width = glow.width = nw; Hh = c.height = mask.height = tmp.height = glow.height = nh;
      if (keep) mx.drawImage(keep, 0, 0, W, Hh);
      dirty = true;
    }
    // both screens fill the frame from the top: the rebuild is a long capture, so only its first screenful shows
    function cover(g, img) { var s = W / img.width; g.drawImage(img, 0, 0, img.width, Math.min(img.height, Hh / s), 0, 0, W, Math.min(Hh, img.height * s)); }
    function render() {
      if (!dirty || !before || !W) return; dirty = false;
      ctx.fillStyle = '#fff'; ctx.fillRect(0, 0, W, Hh);
      cover(ctx, before);
      // the painted edge glows violet, so the reveal reads as a brush in the site's colour
      gx.globalCompositeOperation = 'source-over'; gx.clearRect(0, 0, W, Hh); gx.drawImage(mask, 0, 0);
      gx.globalCompositeOperation = 'source-in'; gx.fillStyle = '#7c3aed'; gx.fillRect(0, 0, W, Hh);
      ctx.save(); ctx.filter = 'blur(' + Math.round(14 * DP) + 'px)'; ctx.globalAlpha = .55; ctx.drawImage(glow, 0, 0); ctx.restore();
      tx.globalCompositeOperation = 'source-over'; tx.clearRect(0, 0, W, Hh); tx.fillStyle = '#fff'; tx.fillRect(0, 0, W, Hh); if (after) cover(tx, after);
      tx.globalCompositeOperation = 'destination-in'; tx.drawImage(mask, 0, 0);
      ctx.drawImage(tmp, 0, 0);
    }
    (function loop() { requestAnimationFrame(loop); if (vis) render(); })();
    function dab(x, y, r) {
      for (var k = 0; k < 4; k++) {
        var ox = (Math.random() - .5) * r * .5, oy = (Math.random() - .5) * r * .5, rr = r * (.75 + Math.random() * .35);
        var g = mx.createRadialGradient(x + ox, y + oy, rr * .35, x + ox, y + oy, rr);
        g.addColorStop(0, 'rgba(0,0,0,.95)'); g.addColorStop(.55, 'rgba(0,0,0,.8)'); g.addColorStop(1, 'rgba(0,0,0,0)');
        mx.fillStyle = g; mx.beginPath(); mx.arc(x + ox, y + oy, rr, 0, Math.PI * 2); mx.fill();
      }
      dirty = true;
    }
    function stroke(x, y) {
      var r = Math.max(60, W / 11);
      if (last) {
        var dx = x - last.x, dy = y - last.y, n = Math.max(1, Math.ceil(Math.hypot(dx, dy) / (r * .3)));
        for (var i = 1; i <= n; i++) dab(last.x + dx * i / n, last.y + dy * i / n, r);
      } else dab(x, y, r);
      last = { x: x, y: y };
    }
    function local(e) { var r = c.getBoundingClientRect(); return { x: (e.clientX - r.left) * DP, y: (e.clientY - r.top) * DP, cx: e.clientX - r.left, cy: e.clientY - r.top }; }
    box.addEventListener('pointermove', function (e) {
      if (auto) return;
      var p = local(e); cur.style.transform = 'translate(' + p.cx + 'px,' + p.cy + 'px)'; box.classList.add('in');
      if (e.pointerType === 'mouse' || e.buttons) { stroke(p.x, p.y); hint.style.opacity = 0; }
    });
    box.addEventListener('pointerleave', function () { last = null; box.classList.remove('in'); });
    box.addEventListener('pointerup', function () { last = null; });
    // a scripted stroke over time (the first one is drawn for you, so the rule is learnt without reading it)
    function play(dur, path, done) {
      if (auto) auto.stop = true;
      last = null;
      var a = { stop: false }, t0 = performance.now(); auto = a;
      (function f(now) {
        if (a.stop) return;
        var k = dur ? Math.min(1, (now - t0) / dur) : 1;
        path(k);
        if (k < 1) requestAnimationFrame(f); else { auto = null; last = null; if (done) done(); }
      })(t0);
    }
    function demo() {
      if (REDUCED) { mx.fillStyle = '#000'; mx.fillRect(W * .5, 0, W * .5, Hh); dirty = true; return; }
      play(1800, function (k) { var t = ease.io(k); stroke(W * (.48 + .5 * t), Hh * (.5 + .36 * Math.sin(t * Math.PI * 3))); });
    }
    function all() {
      var rows = 5;
      play(REDUCED ? 0 : 1600, function (k) {
        var t = k * rows, row = Math.min(rows - 1, Math.floor(t)), f = t - row;
        stroke(W * (row % 2 ? 1 - f : f), Hh * (row + .5) / rows);
      }, function () { mx.fillStyle = '#000'; mx.fillRect(0, 0, W, Hh); dirty = true; });
    }
    function setPair(k) {
      key = k;
      var b = tabs.filter(function (x) { return x.dataset.pair === k; })[0];
      tabs.forEach(function (x) { x.setAttribute('aria-pressed', x === b ? 'true' : 'false'); });
      $$('[data-pair]', root).forEach(function (el) { if (el.tagName !== 'BUTTON') el.hidden = el.dataset.pair !== k; });
      Promise.all([load(b.dataset.before), load(b.dataset.after)]).then(function (im) {
        if (key !== k) return;
        before = im[0]; after = im[1];
        if (auto) auto.stop = true; auto = null;
        mx.clearRect(0, 0, W, Hh); dirty = true; hint.style.opacity = 1;
        if (seen) demo();
      });
    }
    tabs.forEach(function (b) { b.addEventListener('click', function () { setPair(b.dataset.pair); }); });
    $('[data-br="all"]', root).addEventListener('click', all);
    $('[data-br="reset"]', root).addEventListener('click', function () { if (auto) auto.stop = true; auto = null; mx.clearRect(0, 0, W, Hh); dirty = true; hint.style.opacity = 1; });
    size(); addEventListener('resize', size);
    setPair(tabs[0].dataset.pair);
    new IntersectionObserver(function (en) {
      vis = en[0].isIntersecting;
      if (vis) { size(); dirty = true; }
      if (en[0].intersectionRatio >= .45 && !seen) { seen = true; if (before) demo(); }
    }, { threshold: [0, .45] }).observe(box);
  });

  /* ---------- 4. the next-case door ---------- */
  $$('.cs-door').forEach(function (host) {
    var panel = $('.cs-door-panel', host), fill = $('.cs-door-ring .fl', host), num = $('.cs-door-ring b', host);
    var top = $('.cs-door-top', host), hint = $('.cs-door-hint', host), go = $('.cs-door-go', host);
    var url = host.dataset.next;
    var ring = $('.cs-cring', host);
    // the last door draws the home ring as a CSS ring of real screens
    function layoutRing() {
      if (!ring) return;
      var scs = $$('.sc', ring); if (!scs.length) return;
      var h = scs[0].getBoundingClientRect().height || 180;
      var widths = scs.map(function (s) { return +s.dataset.ar * h; });
      var gap = h * .16, circ = widths.reduce(function (a, w) { return a + w + gap; }, 0), R = circ / (2 * Math.PI), acc = 0;
      scs.forEach(function (s, i) { var w = widths[i], a = (acc + w / 2) / R; acc += w + gap;
        s.style.width = w + 'px'; s.style.transform = 'translate(-50%,-50%) rotateY(' + a + 'rad) translateZ(' + R + 'px)'; });
    }
    layoutRing(); addEventListener('resize', layoutRing);
    // the picture of the next page is not a second copy of it
    $$('a,button', panel).forEach(function (a) { a.setAttribute('tabindex', '-1'); });
    var state = 'idle', armed = false, timer = 0, lastY = scrollY, lastT = performance.now(), vel = 0, p = 0;
    var set = function (s) { state = s; host.dataset.state = s; };
    var msg = function (m) { host.dataset.msg = m; };
    // one navigation system for the whole site (transitions.js): the next page knows it came through a door
    // (html.cs-from-door, no entrance, no second animation); the last door brings the home ring back
    function commit() {
      set('committed'); msg('opening');
      var TR = window.TR;
      if (!TR) { location.href = url; return; }
      if (host.dataset.to === 'ring') TR.backToRing('ring');
      else TR.go(url, { kind: 'door' });
    }
    function openNow(e) {
      if (e) e.preventDefault();
      if (state === 'committed') return;
      if (REDUCED) return commit();
      var r = host.getBoundingClientRect(), end = scrollY + r.top + host.offsetHeight - innerHeight;
      set('committed'); msg('opening');
      var y0 = scrollY, t0 = performance.now(), d = 480; // v9.3: 650 ms + 120 ms hold felt like a freeze
      (function stepF(t) { var k = Math.min(1, (t - t0) / d), ee = 1 - Math.pow(1 - k, 3); scrollTo(0, y0 + (end - y0) * ee); render();
        if (k < 1) requestAnimationFrame(stepF); else setTimeout(commit, 40); })(t0);
    }
    go.addEventListener('click', openNow);
    panel.addEventListener('click', openNow);
    function render() {
      var r = host.getBoundingClientRect(), max = host.offsetHeight - innerHeight;
      p = REDUCED ? 1 : clamp(-r.top / Math.max(1, max), 0, 1);
      panel.style.setProperty('--p', p.toFixed(4));
      var pct = Math.round(p * 100);
      fill.setAttribute('stroke-dashoffset', (119.4 * (1 - p)).toFixed(2)); num.textContent = pct;
      if (!REDUCED) { top.style.opacity = Math.max(0, 1 - p * 2.2); hint.style.opacity = p > .02 && p < .45 ? 1 : 0; }
      if (p < .9) armed = true; // only open by itself for people who scrolled into it from above
      if (state === 'committed' || REDUCED) return;
      if (p >= .995 && armed) {
        if (state !== 'arming') {
          set('arming'); msg('arming');
          clearTimeout(timer);
          timer = setTimeout(function () { if (state === 'arming' && p >= .99) commit(); }, Math.abs(vel) > 5000 ? 700 : 260); // v9.3: was 1100 / 420 ms
        }
      } else if (state === 'arming') { set('idle'); clearTimeout(timer); msg('cancel'); }
      else if (state === 'idle' && pct > 0 && host.dataset.msg === 'idle') msg('keep');
    }
    addEventListener('scroll', function () { var t = performance.now(); vel = (scrollY - lastY) / Math.max(1, t - lastT) * 1000; lastY = scrollY; lastT = t; render(); }, { passive: true });
    addEventListener('resize', render);
    addEventListener('pageshow', function (e) { if (e.persisted) { set('idle'); armed = false; msg('again'); render(); } });
    set('idle'); msg('idle'); render();
  });
})();
