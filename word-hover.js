/* "Beam of light" reading effect — applied to ALL text in the page's sections.
   Each word is wrapped in <span class="w">, then tinted by distance from the
   cursor (a soft pool of light following the pointer).
   - Dark backgrounds: words glow ORANGE.
   - Orange / light containers (.grp-card.hot, .cta-band, [data-beam="dark"]):
     words warm to a readable DARK RED.
   Everything is covered by walking whole sections and excluding only the bits
   that shouldn't react (nav, buttons, gradient headings, pills).
   v9.3 (P1): the wrapping used to run synchronously as the page loaded (thousands of spans, a style read and a layout
   read per word), which blocked 0.2 to 0.6 s of every page arrival, right while transitions.js was animating it in.
   Now a section is wrapped only when the pointer first enters it, in idle slices of a few ms, after the page has
   arrived (no html.tr-in); each word's colour is read only when the beam first reaches it, and positions are measured
   only when the pointer moves after something changed. Touch-only devices (no hover) skip it entirely: there is no
   pointer to follow. Generated by Claude (AI assistant). */
(function () {
  if (!matchMedia('(hover: hover)').matches) return;
  var ROOTS = 'section, footer';
  // ancestors whose text should NOT be wrapped
  var EXCLUDE = 'nav, header, .btn, button, .brand, script, style, noscript, ' +
                '.cy, .band .v, h1, .gname, .badge-live, .tag, .grp-title, .arc, ' +
                '.chips, .comp-chips, .cert-chips, .tools, ' +
                /* .url is a flex row: wrapping its words turns them into flex items,
                   and flex discards the whitespace between them, so "a / b" renders "a/b".
                   It is fake browser chrome anyway, so it stays out of the beam. */
                '.win .url, ' +
                /* v9.1: the home hero (hero-ring.js) measures its name word by word for the
                   physics; extra spans would break that. It has its own EN/FR strings too. */
                '.rh, .ap';   /* .ap: the About pile (about-hero.js) measures the name and moves the parts */
  var DARK_SEL = '.grp-card.hot, .cta-band, [data-beam="dark"]';

  var R = 62;                       // beam radius (px)
  function readAccent() {
    try {
      var v = getComputedStyle(document.documentElement).getPropertyValue('--a2-rgb').trim();
      if (v) return v.split(',').map(Number);
    } catch (e) {}
    return [255, 138, 60];
  }      // beam colour on dark backgrounds
  function readLit() {
    try {
      var h = getComputedStyle(document.documentElement).getPropertyValue('--a-on-2').trim();
      if (h && h.charAt(0) === '#' && h.length === 7) {
        return [parseInt(h.substr(1, 2), 16), parseInt(h.substr(3, 2), 16), parseInt(h.substr(5, 2), 16)];
      }
    } catch (e) {}
    return [58, 24, 8];
  }
  var ORANGE = readAccent();
  var LIT = readLit();
  addEventListener('theme:changed', function () { ORANGE = readAccent(); LIT = readLit(); });          // beam colour on orange/light containers (dark red)

  var words = [];
  var mx = -1e5, my = -1e5, raf = 0;

  function parseRGB(str) {
    var m = str.match(/(\d+),\s*(\d+),\s*(\d+)/);
    return m ? [+m[1], +m[2], +m[3]] : [163, 158, 152];
  }

  var pending = [];
  function wrap(root) {
    if (root.dataset.ww) return;
    root.dataset.ww = '1';
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) {
        if (!n.nodeValue || !n.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        var p = n.parentElement;
        if (!p || p.classList.contains('w') || p.closest(EXCLUDE)) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    var n;
    while ((n = walker.nextNode())) pending.push(n);
  }
  function split(node) {
    if (!node.parentNode || !node.isConnected) return;
    var parts = node.nodeValue.split(/(\s+)/);
    var frag = document.createDocumentFragment();
    parts.forEach(function (p) {
      if (!p) return;
      if (/^\s+$/.test(p)) { frag.appendChild(document.createTextNode(p)); return; }
      var s = document.createElement('span');
      s.className = 'w';
      s.textContent = p;
      frag.appendChild(s);
    });
    node.parentNode.replaceChild(frag, node);
  }

  function collect() {
    words = [];
    var spans = document.querySelectorAll('.w');
    for (var i = 0; i < spans.length; i++) {
      var el = spans[i];
      words.push({ el: el, cx: 0, cy: 0, base: null, target: null, lit: false });
    }
    dirty = true;
  }

  // positions are read lazily: on the first pointer move after a change (load, resize, language, accordion)
  var dirty = true;
  function measure() { dirty = true; }
  function measureNow() {
    dirty = false;
    var sx = window.pageXOffset, sy = window.pageYOffset;
    for (var i = 0; i < words.length; i++) {
      var r = words[i].el.getBoundingClientRect();
      words[i].cx = r.left + r.width / 2 + sx;
      words[i].cy = r.top + r.height / 2 + sy;
    }
  }

  function update() {
    raf = 0;
    if (dirty) measureNow();
    var R2 = R * R;
    for (var i = 0; i < words.length; i++) {
      var w = words[i];
      var dx = w.cx - mx, dy = w.cy - my, d2 = dx * dx + dy * dy;
      if (d2 < R2) {
        if (!w.base) { w.base = parseRGB(getComputedStyle(w.el).color); w.target = w.el.closest(DARK_SEL) ? LIT : ORANGE; }
        var t = 1 - Math.sqrt(d2) / R; t = t * t * (3 - 2 * t);
        var b = w.base, g = w.target;
        w.el.style.color = 'rgb(' +
          Math.round(b[0] + (g[0] - b[0]) * t) + ',' +
          Math.round(b[1] + (g[1] - b[1]) * t) + ',' +
          Math.round(b[2] + (g[2] - b[2]) * t) + ')';
        w.lit = true;
      } else if (w.lit) {
        w.el.style.color = '';
        w.lit = false;
      }
    }
  }

  function onMove(e) { mx = e.pageX; my = e.pageY; if (!raf) raf = requestAnimationFrame(update); }
  function clearBeam() { mx = my = -1e5; if (!raf) raf = requestAnimationFrame(update); }

  // a section is wrapped when the pointer first enters it, a few ms per idle slice, once the page has arrived
  var idle = window.requestIdleCallback ? function (f) { requestIdleCallback(f, { timeout: 300 }); } : function (f) { setTimeout(f, 30); };
  var H = document.documentElement, running = false;
  function work() {
    if (/\btr-in\b/.test(H.className)) return setTimeout(work, 150);
    var t0 = performance.now();
    while (pending.length && performance.now() - t0 < 5) split(pending.shift());
    if (pending.length) return idle(work);
    running = false; collect();
  }
  function enter(root) {
    if (!root || root.dataset.ww) return;
    wrap(root);
    if (!running) { running = true; idle(work); }
  }
  document.addEventListener('pointerover', function (e) { var r = e.target.closest && e.target.closest(ROOTS); if (r) enter(r); }, { passive: true });
  /* Switching language replaces innerHTML, which discards every <span class="w">
     this effect depends on. Clear the "already wrapped" marks and wrap again. */
  addEventListener('i18n:changed', function () {
    var roots = document.querySelectorAll(ROOTS);
    for (var i = 0; i < roots.length; i++) delete roots[i].dataset.ww;
    pending = []; collect();
  });

  window.addEventListener('pointermove', onMove, { passive: true });
  document.addEventListener('mouseleave', clearBeam);
  var rt;
  window.addEventListener('resize', function () { clearTimeout(rt); rt = setTimeout(measure, 150); });
  window.addEventListener('load', function () { setTimeout(measure, 300); });
  window.addEventListener('beam:remeasure', function () { setTimeout(measure, 430); }); // after accordion opens
})();
